export function getCharacterSpecialization(settings: StoryImageSettings) {
  const id = settings.visual.characterSpecialization ?? 'none';
  const preset = CHARACTER_SPECIALIZATIONS.find(p => p.id === id) ?? CHARACTER_SPECIALIZATIONS[0];
  const content = settings.visual.characterSpecializationEdits?.[preset.id] ?? preset.content;
  return { ...preset, content: preset.id === 'none' ? '' : content };
}
