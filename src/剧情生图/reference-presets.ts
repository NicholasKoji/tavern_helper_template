function resolvePreset(presets: ReferencePreset[], id: string | undefined, custom: string | undefined) {
  const preset = presets.find(item => item.id === id) ?? presets[0];
  const customText = (custom ?? '').trim();
  if (preset.id === 'custom') return customText;
  return preset.prompt;
}

export function resolveReferenceOutfitStyle(id?: string, custom?: string) {
  return resolvePreset(REFERENCE_OUTFIT_STYLES, id, custom);
}

export function resolveReferencePhotoStyle(id?: string, custom?: string) {
  return resolvePreset(REFERENCE_PHOTO_STYLES, id, custom);
}
